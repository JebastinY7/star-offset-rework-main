import { useEffect, useRef, useState } from "react";
import { useSearchParams } from "react-router-dom";
import api, { errorText } from "../api";
import Icon from "../components/Icon";
import Pagination from "../components/Pagination";

// Settings > Vendor Management (admin only). Opened from Settings.jsx, which passes its shared UI helpers.
// Vendors are outside printers who receive part of a shop order. They sign in to the separate Vendor Portal.
// The open screen lives in the URL, so Back / refresh work:
//   /settings?tab=vendors                  list
//   /settings?tab=vendors&view=add         add form
//   /settings?tab=vendors&view=edit&id=3   edit form
//   /settings?tab=vendors&view=detail&id=3 read-only details

const PAGE_SIZE = 10;
const MIN_PASSWORD_LEN = 6; // same rule as the server
const TITLE = "Vendor Management";
const SUBTITLE = "Manage outside printers who produce jobs for Star Offset and their portal access.";

const cleanMobile = (v) => {
  let d = v.replace(/\D/g, "");
  if (d.length === 12 && d.startsWith("91")) d = d.slice(2); // pasted as +91 98765 43210
  return d.slice(0, 10);
};

const BLANK = {
  name: "", owner_name: "", phone: "", email: "", specialties: "", works: [], address: "",
  username: "", password: "", // username = the vendor's User ID: generated by the server (e.g. 2026V0001), shown read-only
  is_active: "true", portal_access: true, notes: "",
};

// same rule as the server's rate_key: "Bill  BOOK" and "bill book" are the same work
const norm = (s) => String(s || "").toLowerCase().split(/\s+/).filter(Boolean).join(" ");
const KIND = { normal: "Offset", digital: "Digital" };
const kindText = (kinds = []) => kinds.map((k) => KIND[k] || k).join(" + ");

const fmtDate = (iso) => new Date(iso).toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });

const Field = ({ label, required, children }) => (
  <label><span className="lbl">{label}{required && <> <span className="req">*</span></>}</span>{children}</label>
);

// the server has no single-vendor GET, so the form / detail screens pick the vendor out of the list
async function loadVendor(id) {
  const r = await api.get("/settings/vendors/");
  const v = r.data.results.find((x) => String(x.id) === String(id));
  if (!v) throw new Error("Vendor not found.");
  return v;
}
const fail = (err) => (err instanceof Error && !err.response ? err.message : errorText(err));

/* ------------------------------------------------------- reset password */
function VendorPasswordModal({ vendor, PasswordInput, onClose, onDone }) {
  const [pw, setPw] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");

  const save = async (e) => {
    e.preventDefault();
    setError(""); setBusy(true);
    try {
      await api.patch(`/settings/vendors/${vendor.id}/`, { password: pw });
      onDone();
    } catch (err) { setError(errorText(err)); setBusy(false); }
  };

  return (
    <div className="modal-bg">
      <form className="card modal" role="dialog" aria-modal="true" onClick={(e) => e.stopPropagation()} onSubmit={save}>
        <h2>Vendor Password</h2>
        <p className="muted" style={{ margin: 0 }}>{vendor.name} · {vendor.username}</p>
        {error && <div className="error">{error}</div>}
        <PasswordInput label="New password" value={pw} onChange={(e) => setPw(e.target.value)} minLength={MIN_PASSWORD_LEN} autoComplete="new-password" required autoFocus />
        <div className="row">
          <button type="button" disabled={busy} onClick={onClose}>Cancel</button>
          <button className="primary" disabled={busy}>{busy ? "Please wait…" : "Save Password"}</button>
        </div>
      </form>
    </div>
  );
}

/* ------------------------------------------------- "which works do they do" */
// options = every work in the price list (offset + digital); value = the work names ticked for this vendor.
// A work sold both ways (e.g. Visiting Card) is one chip tagged "Offset + Digital".
function WorkPicker({ options, value, onChange, loading }) {
  const [t, setT] = useState("");
  const on = new Set(value.map(norm));
  const term = t.trim().toLowerCase();
  const shown = options.filter((w) => !term || w.name.toLowerCase().includes(term));
  // works the vendor still has but that were removed from the price list: keep them visible so they can be unticked
  const orphans = value.filter((x) => !options.some((o) => o.key === norm(x)));

  const toggle = (w) => onChange(on.has(w.key) ? value.filter((x) => norm(x) !== w.key) : [...value, w.name]);
  const allShownOn = shown.length > 0 && shown.every((w) => on.has(w.key));
  const toggleShown = () => onChange(allShownOn
    ? value.filter((x) => !shown.some((w) => w.key === norm(x)))
    : [...value, ...shown.filter((w) => !on.has(w.key)).map((w) => w.name)]);

  if (loading) return <p className="muted">Loading works…</p>;
  if (options.length === 0 && orphans.length === 0) return <p className="st-hint">No works found. Add services in Pricing first, then mark them here.</p>;

  return (
    <div className="st-works">
      <div className="st-works-bar">
        <b>{value.length} of {options.length} selected</b>
        {options.length > 8 && (
          <div className="search-box"><Icon name="search" size={15} /><input value={t} onChange={(e) => setT(e.target.value)} placeholder="Search works…" aria-label="Search works" /></div>
        )}
        {shown.length > 0 && <button type="button" className="st-works-all" onClick={toggleShown}>{allShownOn ? "Clear" : term ? "Select shown" : "Select all"}</button>}
      </div>
      <div className="st-work-grid" role="group" aria-label="Works this vendor does">
        {shown.map((w) => (
          <button type="button" key={w.key} role="checkbox" aria-checked={on.has(w.key)} className={`st-work${on.has(w.key) ? " on" : ""}`} onClick={() => toggle(w)}>
            <span className="st-work-tick">{on.has(w.key) && <Icon name="check" size={12} />}</span>
            <span className="st-work-name">{w.name}</span>
            <small className={w.kinds.length > 1 ? "dual" : ""}>{kindText(w.kinds)}</small>
          </button>
        ))}
        {orphans.map((x) => (
          <button type="button" key={`o-${x}`} role="checkbox" aria-checked="true" className="st-work on gone" title="No longer in the price list" onClick={() => onChange(value.filter((y) => y !== x))}>
            <span className="st-work-tick"><Icon name="check" size={12} /></span><span className="st-work-name">{x}</span><small>Removed</small>
          </button>
        ))}
        {shown.length === 0 && <p className="st-hint">No work matches “{t}”.</p>}
      </div>
    </div>
  );
}

/* -------------------------------------------------------------- the form */
function VendorForm({ id, PasswordInput, onBack, onSaved }) {
  const editing = Boolean(id);
  const [f, setF] = useState(BLANK);
  const [loading, setLoading] = useState(editing);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [workList, setWorkList] = useState([]);
  const [worksLoading, setWorksLoading] = useState(true);
  const top = useRef(null);

  useEffect(() => {
    api.get("/settings/vendor-works/")
      .then((r) => setWorkList(r.data.results || []))
      .catch((err) => setError(errorText(err)))
      .finally(() => setWorksLoading(false));
  }, []);

  useEffect(() => {
    if (!editing) return;
    loadVendor(id)
      .then((v) => setF({ ...BLANK, name: v.name, owner_name: v.owner_name, phone: v.phone, email: v.email, specialties: v.specialties, works: v.works || [],
        address: v.address, username: v.username, is_active: String(v.is_active), portal_access: v.portal_access, notes: v.notes }))
      .catch((err) => setError(fail(err)))
      .finally(() => setLoading(false));
  }, [id, editing]);

  const set = (k) => (e) => setF({ ...f, [k]: e.target.value });

  const submit = async (another) => {
    setError(""); setBusy(true);
    try {
      const body = { name: f.name, owner_name: f.owner_name, phone: f.phone, email: f.email.trim(), specialties: f.specialties, works: f.works, address: f.address, notes: f.notes };
      if (editing) {
        await api.patch(`/settings/vendors/${id}/`, { ...body, is_active: f.is_active === "true", portal_access: f.portal_access });
        onSaved(`Vendor ${f.name} updated`);
        return;
      }
      const r = await api.post("/settings/vendors/", { ...body, password: f.password }); // the server generates the User ID
      const msg = `Vendor ${f.name} created · User ID ${r.data.vendor.username}`;
      if (another) { setF(BLANK); top.current?.scrollIntoView({ behavior: "smooth", block: "start" }); onSaved(msg, true); }
      else onSaved(msg);
    } catch (err) {
      setError(errorText(err));
      top.current?.scrollIntoView({ behavior: "smooth", block: "start" });
    } finally { setBusy(false); }
  };

  // the button that was pressed decides "save" or "save and add another"
  const submitter = useRef("save");
  const onSubmit = (e) => { e.preventDefault(); submit(submitter.current === "another"); };

  if (loading) return <p className="muted">Loading…</p>;

  return (
    <form className="shop-form" onSubmit={onSubmit} ref={top}>
      <button type="button" className="shop-back" onClick={onBack}><Icon name="arrowLeft" size={16} /> Back to Vendor Management</button>
      <div>
        <h3 style={{ margin: 0 }}>{editing ? "Edit Vendor" : "Add New Vendor"}</h3>
        <p className="muted" style={{ margin: "2px 0 0" }}>{editing ? "Update the vendor profile and its portal access." : "Create a vendor profile and grant access to the Vendor Portal."}</p>
      </div>
      {error && <div className="error">{error}</div>}

      <section className="shop-sec">
        <h4><span className="num">01</span> Business details</h4>
        <div className="st-grid2">
          <Field label="Vendor / Business Name" required><input value={f.name} onChange={set("name")} maxLength={150} autoComplete="off" required autoFocus /></Field>
          <Field label="Owner / Contact Person" required><input value={f.owner_name} onChange={set("owner_name")} maxLength={100} autoComplete="off" required /></Field>
          <Field label="Mobile Number" required>
            <input type="tel" inputMode="numeric" value={f.phone} onChange={(e) => setF({ ...f, phone: cleanMobile(e.target.value) })}
              maxLength={12} pattern="[0-9]{10}" title="Enter a 10 digit mobile number" autoComplete="off" required />
          </Field>
          <Field label="Email Address" required><input type="email" value={f.email} onChange={set("email")} autoComplete="off" required /></Field>
        </div>
        <Field label="Address"><textarea rows={3} value={f.address} onChange={set("address")} maxLength={500} /></Field>
      </section>

      <section className="shop-sec">
        <h4><span className="num">02</span> Works this vendor does</h4>
        <p className="st-hint">Tick every work this vendor can produce. When you assign an order, only the vendors who do that work are shown.</p>
        <WorkPicker options={workList} value={f.works} onChange={(works) => setF((p) => ({ ...p, works }))} loading={worksLoading} />
        <Field label="Other specialties (Optional)">
          <input value={f.specialties} onChange={set("specialties")} maxLength={250} autoComplete="off" placeholder="Anything not in the list above, e.g. Binding" />
        </Field>
      </section>

      <section className="shop-sec">
        <h4><span className="num">03</span> Portal login</h4>
        <div className="st-grid2">
          <Field label="User ID">
            <input value={editing ? f.username : ""} placeholder="Auto-generated when you save (e.g. 2026V0001)" readOnly disabled title="The User ID is generated automatically and cannot be changed" />
          </Field>
          {editing ? (
            <Field label="Account Status" required>
              <select value={f.is_active} onChange={set("is_active")}><option value="true">Active</option><option value="false">Inactive</option></select>
            </Field>
          ) : (
            <PasswordInput label="Password" value={f.password} onChange={set("password")} minLength={MIN_PASSWORD_LEN} autoComplete="new-password" required />
          )}
        </div>
        {editing && (
          <label className="shop-check"><input type="checkbox" checked={f.portal_access} onChange={(e) => setF({ ...f, portal_access: e.target.checked })} /> Allow vendor to log in to the Vendor Portal</label>
        )}
        {editing
          ? <p className="st-hint">To reset the password, use “More” on the vendor list.</p>
          : <p className="st-hint">The User ID is generated automatically when you save. Share the User ID and password with the vendor; they can sign in to the Vendor Portal right away.</p>}
      </section>

      <section className="shop-sec">
        <h4><span className="num">04</span> Internal notes (Optional)</h4>
        <textarea rows={3} value={f.notes} onChange={set("notes")} maxLength={1000} aria-label="Internal notes" placeholder="Only visible to admins" />
      </section>

      <div className="shop-bar">
        <button type="button" disabled={busy} onClick={onBack}>Cancel</button>
        <button className="primary" disabled={busy} onClick={() => { submitter.current = "save"; }}>{busy ? "Saving…" : editing ? "Save Changes" : "Save Vendor"}</button>
        {!editing && <button disabled={busy} onClick={() => { submitter.current = "another"; }}>Save &amp; Add Another</button>}
      </div>
    </form>
  );
}

/* --------------------------------------------------------------- details */
function VendorDetail({ id, onBack, onEdit }) {
  const [v, setV] = useState(null);
  const [error, setError] = useState("");
  useEffect(() => { loadVendor(id).then(setV).catch((err) => setError(fail(err))); }, [id]);

  const rows = v && [
    ["Vendor / Business", v.name], ["Owner / Contact", v.owner_name], ["Mobile", v.phone], ["Email", v.email],
    ["Works", (v.works || []).length ? v.works.join(", ") : "Not set"], ["Other Specialties", v.specialties || "—"], ["Address", v.address || "—"],
    ["User ID", v.username], ["Portal Access", v.portal_access ? "Enabled" : "Disabled"], ["Account Status", v.is_active ? "Active" : "Inactive"],
    ["Open Jobs", v.open_jobs], ["Added On", fmtDate(v.created_at)], ["Internal Notes", v.notes || "—"],
  ];

  return (
    <div className="shop-form">
      <button type="button" className="shop-back" onClick={onBack}><Icon name="arrowLeft" size={16} /> Back to Vendor Management</button>
      {error && <div className="error">{error}</div>}
      {!v && !error && <p className="muted">Loading…</p>}
      {v && (
        <>
          <div className="between row">
            <h3 style={{ margin: 0 }}>{v.name}</h3>
            <button type="button" className="primary" onClick={onEdit}><Icon name="edit" size={16} /> Edit</button>
          </div>
          <dl className="shop-dl">
            {rows.map(([k, val]) => <div key={k}><dt>{k}</dt><dd>{val}</dd></div>)}
          </dl>
        </>
      )}
    </div>
  );
}

/* ------------------------------------------------------------------ list */
export default function VendorsPanel({ Panel, Flash, useFlash, PasswordInput }) {
  const [sp, setSp] = useSearchParams();
  const view = sp.get("view") || "list";
  const id = sp.get("id");
  const go = (params) => setSp({ tab: "vendors", ...params });

  const [flash, ok, bad, clear] = useFlash();

  const [all, setAll] = useState([]);
  const [loading, setLoading] = useState(true);
  const [q, setQ] = useState("");
  const [status, setStatus] = useState("");
  const [account, setAccount] = useState("");
  const [page, setPage] = useState(1);
  const [tick, setTick] = useState(0); // reload after an action
  const [menu, setMenu] = useState(null); // { vendor, top, right }
  const [pwFor, setPwFor] = useState(null);
  const [delFor, setDelFor] = useState(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    if (view !== "list") return;
    let stale = false;
    setLoading(true);
    api.get("/settings/vendors/")
      .then((r) => { if (!stale) setAll(r.data.results); })
      .catch((err) => { if (!stale) bad(err); })
      .finally(() => { if (!stale) setLoading(false); });
    return () => { stale = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [view, tick]);

  // close the "more" dropdown on outside click / scroll / resize
  useEffect(() => {
    if (!menu) return;
    const close = () => setMenu(null);
    const onDown = (e) => { if (!e.target.closest(".st-pop") && !e.target.closest(".bh-ico.more")) close(); };
    document.addEventListener("mousedown", onDown);
    window.addEventListener("scroll", close, true);
    window.addEventListener("resize", close);
    return () => { document.removeEventListener("mousedown", onDown); window.removeEventListener("scroll", close, true); window.removeEventListener("resize", close); };
  }, [menu]);

  const filtered = Boolean(q || status || account);
  const reset = () => { setQ(""); setStatus(""); setAccount(""); setPage(1); };
  const pick = (setter) => (e) => { setter(e.target.value); setPage(1); };

  const openMenu = (e, v) => {
    if (menu?.vendor.id === v.id) { setMenu(null); return; }
    const r = e.currentTarget.getBoundingClientRect();
    setMenu({ vendor: v, top: r.bottom + 4, right: window.innerWidth - r.right });
  };

  // the server edits flags through PATCH (no separate toggle routes)
  const patchFlag = async (v, body, message) => {
    clear(); setMenu(null);
    try { await api.patch(`/settings/vendors/${v.id}/`, body); ok(message); setTick((n) => n + 1); }
    catch (err) { bad(err); }
  };

  const remove = async () => {
    clear(); setBusy(true);
    try { await api.delete(`/settings/vendors/${delFor.id}/`); ok("Vendor deleted successfully"); setTick((n) => n + 1); }
    catch (err) { bad(err); }
    setBusy(false); setDelFor(null);
  };

  /* ---- add / edit / detail screens */
  if (view === "add" || view === "edit") {
    return (
      <Panel title={TITLE} subtitle={SUBTITLE}>
        <Flash flash={flash} />
        <VendorForm
          key={view + (id || "")}
          id={view === "edit" ? id : null}
          PasswordInput={PasswordInput}
          onBack={() => go({})}
          onSaved={(msg, stay) => { ok(msg); if (!stay) go({}); }}
        />
      </Panel>
    );
  }
  if (view === "detail") {
    return (
      <Panel title={TITLE} subtitle={SUBTITLE}>
        <VendorDetail id={id} onBack={() => go({})} onEdit={() => go({ view: "edit", id })} />
      </Panel>
    );
  }

  /* ---- list (search + filters run in the browser: a shop has few vendors) */
  const term = q.trim().toLowerCase();
  const rows = all.filter((v) =>
    (!term || [v.name, v.owner_name, v.phone, v.email, v.username, v.specialties, (v.works || []).join(" ")].some((x) => (x || "").toLowerCase().includes(term))) &&
    (!status || (status === "active") === v.is_active) &&
    (!account || (account === "enabled") === v.portal_access));
  const count = rows.length;
  const pages = Math.max(1, Math.ceil(count / PAGE_SIZE));
  const cur = Math.min(page, pages);
  const shown = rows.slice((cur - 1) * PAGE_SIZE, cur * PAGE_SIZE);
  const first = count ? (cur - 1) * PAGE_SIZE + 1 : 0;
  const last = Math.min(cur * PAGE_SIZE, count);

  const month = new Date().toISOString().slice(0, 7);
  const stats = {
    total: all.length,
    active: all.filter((v) => v.is_active).length,
    inactive: all.filter((v) => !v.is_active).length,
    open: all.reduce((n, v) => n + (v.open_jobs || 0), 0),
    fresh: all.filter((v) => (v.created_at || "").slice(0, 7) === month).length,
  };

  return (
    <Panel
      title={TITLE}
      subtitle={SUBTITLE}
      action={<button type="button" className="primary" onClick={() => { clear(); go({ view: "add" }); }}><Icon name="plus" size={16} /> Add New Vendor</button>}
    >
      <Flash flash={flash} />

      <div className="st-stats shop-stats">
        <div className="st-stat"><b>{stats.total}</b><span>Total Vendors</span></div>
        <div className="st-stat active"><b>{stats.active}</b><span>Active Vendors</span></div>
        <div className="st-stat failed"><b>{stats.inactive}</b><span>Inactive Vendors</span></div>
        <div className="st-stat admins"><b>{stats.open}</b><span>Open Jobs</span></div>
      </div>

      <div className="st-filters shop-filters">
        <div className="search-box">
          <Icon name="search" size={16} />
          <input placeholder="Search vendor, contact, mobile, email, User ID or work…" value={q} onChange={pick(setQ)} aria-label="Search vendors" />
        </div>
        <select value={status} onChange={pick(setStatus)} aria-label="Status">
          <option value="">All Status</option><option value="active">Active</option><option value="inactive">Inactive</option>
        </select>
        <select value={account} onChange={pick(setAccount)} aria-label="Portal access">
          <option value="">All Accounts</option><option value="enabled">Portal enabled</option><option value="disabled">Portal disabled</option>
        </select>
        <button type="button" disabled={!filtered} onClick={reset}>Reset Filters</button>
      </div>

      <div className="between row">
        <b className="shop-dir">Vendor Directory</b>
        <span className="muted">Showing {count} vendor{count === 1 ? "" : "s"}{stats.fresh ? ` · ${stats.fresh} new this month` : ""}</span>
      </div>

      <div className="st-table-wrap">
        <table className="st-table shop-table">
          <thead><tr><th>Vendor / Business</th><th>Contact</th><th>User ID</th><th>Open Jobs</th><th>Portal Access</th><th>Status</th><th style={{ textAlign: "right" }}>Actions</th></tr></thead>
          <tbody>
            {loading && shown.length === 0 && <tr><td colSpan={7} className="st-empty">Loading…</td></tr>}
            {!loading && shown.length === 0 && <tr><td colSpan={7} className="st-empty">{filtered ? "No vendors match these filters" : "No vendors added yet"}</td></tr>}
            {shown.map((v) => (
              <tr key={v.id}>
                <td><div className="st-contact"><b>{v.name}</b>
                  {(v.works || []).length > 0
                    ? <span className="muted" title={v.works.join(", ")}>{v.works.slice(0, 3).join(", ")}{v.works.length > 3 ? ` +${v.works.length - 3} more` : ""}</span>
                    : <span className="muted st-nowork">{v.specialties || "No works marked"}</span>}</div></td>
                <td><div className="st-contact"><span>{v.owner_name}</span><span className="muted">{v.phone}</span></div></td>
                <td><div className="st-contact"><span>{v.username}</span><span className="muted">{v.email}</span></div></td>
                <td>{v.open_jobs}</td>
                <td><span className={`pill ${v.portal_access ? "green" : ""}`}>{v.portal_access ? "Enabled" : "Disabled"}</span></td>
                <td><span className={`status ${v.is_active ? "completed" : "cancelled"}`}>● {v.is_active ? "Active" : "Inactive"}</span></td>
                <td>
                  <div className="st-acts">
                    <button type="button" className="bh-ico view" data-tip="View" aria-label={`View ${v.name}`} onClick={() => go({ view: "detail", id: v.id })}><Icon name="eye" size={16} /></button>
                    <button type="button" className="bh-ico edit" data-tip="Edit" aria-label={`Edit ${v.name}`} onClick={() => go({ view: "edit", id: v.id })}><Icon name="edit" size={16} /></button>
                    <button type="button" className="bh-ico more" data-tip="More" aria-label={`More actions for ${v.name}`} aria-haspopup="menu" onClick={(e) => openMenu(e, v)}><Icon name="more" size={16} /></button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      <div className="table-foot">
        <span className="muted">{count ? `Showing ${first}–${last} of ${count} vendor${count === 1 ? "" : "s"}` : "0 vendors"}</span>
        {pages > 1 && <Pagination page={cur} pages={pages} onChange={setPage} />}
      </div>

      {menu && (
        <div className="st-pop" role="menu" style={{ top: menu.top, right: menu.right }}>
          <button type="button" role="menuitem" onClick={() => { setPwFor(menu.vendor); setMenu(null); }}><Icon name="lock" size={16} />Reset password</button>
          <button type="button" role="menuitem" onClick={() => patchFlag(menu.vendor, { portal_access: !menu.vendor.portal_access }, `Portal access ${menu.vendor.portal_access ? "disabled" : "enabled"} for ${menu.vendor.name}`)}>
            <Icon name={menu.vendor.portal_access ? "block" : "unlock"} size={16} />{menu.vendor.portal_access ? "Disable portal access" : "Enable portal access"}
          </button>
          <button type="button" role="menuitem" onClick={() => patchFlag(menu.vendor, { is_active: !menu.vendor.is_active }, `${menu.vendor.name} ${menu.vendor.is_active ? "deactivated" : "activated"}`)}>
            <Icon name={menu.vendor.is_active ? "block" : "check"} size={16} />{menu.vendor.is_active ? "Deactivate account" : "Activate account"}
          </button>
          <button type="button" role="menuitem" className="danger" onClick={() => { setDelFor(menu.vendor); setMenu(null); }}><Icon name="trash" size={16} />Delete vendor</button>
        </div>
      )}

      {pwFor && (
        <VendorPasswordModal
          vendor={pwFor}
          PasswordInput={PasswordInput}
          onClose={() => setPwFor(null)}
          onDone={() => { ok(`Password updated for ${pwFor.name}`); setPwFor(null); }}
        />
      )}
      {delFor && (
        <div className="modal-bg">
          <div className="card modal" role="dialog" aria-modal="true" onClick={(e) => e.stopPropagation()}>
            <h2>Delete Vendor</h2>
            <p style={{ margin: 0 }}>Are you sure you want to delete <strong>{delFor.name}</strong>? Its portal login will be removed too. A vendor that already has jobs cannot be deleted; deactivate it instead.</p>
            <div className="row">
              <button disabled={busy} onClick={() => setDelFor(null)}>Cancel</button>
              <button className="danger" disabled={busy} onClick={remove}>{busy ? "Please wait…" : "Yes, delete"}</button>
            </div>
          </div>
        </div>
      )}
    </Panel>
  );
}
