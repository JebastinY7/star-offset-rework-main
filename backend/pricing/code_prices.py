def _norm(value):
    return " ".join(str(value or "").strip().casefold().split())


def iter_price_rules():
    for row in PRICE_RULES:
        yield CodePriceRule(row[0], row[1], row[2], row[3], row[4], Decimal(row[5]), row[6], row[7], row[8])


_UNSET = object()


def get_price_rules(category_name=None, size_name=_UNSET, variant_name=_UNSET):
    """Return configured rules, optionally filtered by DB option names.

    Passing variant_name=None explicitly matches only rules without a variant;
    omitting variant_name leaves that dimension unfiltered.
    """
    c = _norm(category_name) if category_name is not None else ""
    s = _norm(size_name) if size_name is not _UNSET and size_name is not None else ""
    v = _norm(variant_name) if variant_name is not _UNSET and variant_name is not None else ""
    return [r for r in iter_price_rules()
            if (not c or _norm(r.category_name) == c)
            and (size_name is _UNSET or _norm(r.size_name) == s)
            and (variant_name is _UNSET or _norm(r.variant_name) == v)]


def get_price_rule(category_name, size_name, variant_name, qty):
    """Resolve a quantity slab; return None when the code has no configured price."""
    rules = get_price_rules(category_name, size_name, variant_name)
    matching = [r for r in rules if r.min_qty <= qty and (r.max_qty is None or qty <= r.max_qty)]
    if matching:
        return sorted(matching, key=lambda r: r.min_qty)[0]
    return None

def get_latest_price_rule(category_name, size_name, variant_name):
    rules = get_price_rules(category_name, size_name, variant_name)
    return max(rules, key=lambda r: r.min_qty) if rules else None


